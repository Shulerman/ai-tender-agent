import json

from pydantic import ValidationError

from app.ai.gemini import generate_text
from app.ai.technical_models import TechnicalAnalysis


async def analyze_technical_requirements(document_text: str) -> dict:
    """
    Анализирует техническое задание закупки с помощью Gemini
    и проверяет структуру результата через Pydantic.
    """

    if not isinstance(document_text, str) or not document_text.strip():
        raise ValueError("Текст документа пуст")

    prompt = f"""
Ты — технический аналитик государственных и коммерческих закупок.

Твоя задача — тщательно проанализировать документацию закупки
и извлечь все технические и организационные требования.

ОСНОВНЫЕ ПРАВИЛА АНАЛИЗА

1. ТОВАРЫ И МАТЕРИАЛЫ

Выдели все товары, материалы, комплектующие и оборудование,
которые заказчик требует поставить.

Для каждого товара укажи:

- name: наименование;
- quantity: количество в исходной формулировке;
- unit: единица измерения;
- technical_characteristics: технические характеристики;
- packaging_requirements: требования к упаковке;
- quality_and_standards: требования к качеству и стандартам;
- quotes: точные цитаты из документа.

Не объединяй разные товары в одну позицию.
Не теряй отдельные характеристики и дополнительные требования.

2. СРОКИ И УСЛОВИЯ ПОСТАВКИ

Найди все сведения о сроках поставки во всём документе,
включая техническое задание, проект контракта, приложения
и дополнительные разделы.

Учитывай:
- общие сроки поставки;
- сроки после заключения контракта;
- сроки после получения заявки;
- отдельные сроки для разных партий;
- срочные поставки;
- графики и этапы поставки.

Если срок указан, обязательно извлеки его.
Не заменяй известный срок значением «Не указано».

Для каждого требования укажи:
- delivery_time: срок поставки в исходной формулировке;
- delivery_address: адрес поставки, если он указан;
- quotes: точные цитаты из документа.

3. ДОКУМЕНТЫ И ПОДТВЕРЖДЕНИЯ

Выдели все требования к:
- сертификатам;
- декларациям соответствия;
- паспортам качества;
- регистрационным удостоверениям;
- образцам продукции;
- протоколам испытаний;
- лицензиям;
- иным документам и подтверждениям.

Для каждого требования укажи точные цитаты.

4. РИСКИ И НЕОПРЕДЕЛЁННОСТИ

Найди:
- противоречия между разделами документации;
- несовпадающие характеристики;
- неоднозначные требования;
- отсутствующие важные параметры;
- нереалистичные или трудноисполнимые сроки;
- неопределённые условия приёмки;
- требования, которые могут ограничить круг поставщиков;
- другие технические и организационные риски.

Для каждого риска приведи подтверждающие цитаты.

Не называй требование нарушением закона.
Юридическую оценку выполняет отдельный юридический анализатор.

5. ВОПРОСЫ ЗАКАЗЧИКУ

Составь конкретные вопросы, ответы на которые необходимы
для подготовки корректного коммерческого предложения
и исполнения контракта.

Не задавай вопросы, ответы на которые прямо содержатся
в документации.

ВАЖНЫЕ ПРАВИЛА ДОСТОВЕРНОСТИ

- Не придумывай отсутствующие сведения.
- Не делай предположений о характеристиках товаров.
- Не изменяй исходные количества и единицы измерения.
- Не преобразуй приблизительные сроки в точные даты.
- Не смешивай требования разных товаров.
- Не считай отсутствие информации доказательством отсутствия требования.
- Для существенных выводов обязательно приводи точные цитаты.
- Если сведения отсутствуют, используй значение «Не указано».
- Если требование сформулировано неоднозначно, сохрани исходную
  формулировку и отрази неопределённость в рисках.

ФОРМАТ ОТВЕТА

Верни только корректный JSON без Markdown-разметки
и пояснений за пределами JSON.

Структура:

{{
  "products": [],
  "delivery_requirements": [],
  "document_requirements": [],
  "risks_and_uncertainties": [],
  "questions_to_customer": []
}}

ТЕКСТ ДОКУМЕНТА ДЛЯ АНАЛИЗА:

{document_text}
"""

    result = await generate_text(prompt, json_mode=True)
    result = result.strip()

    if result.startswith("```json"):
        result = result[7:]
    elif result.startswith("```"):
        result = result[3:]

    if result.endswith("```"):
        result = result[:-3]

    result = result.strip()

    try:
        parsed_result = json.loads(result)
    except json.JSONDecodeError as error:
        raise RuntimeError(
            f"Gemini вернул некорректный JSON: {error}"
        ) from error

    try:
        validated_result = TechnicalAnalysis.model_validate(parsed_result)
    except ValidationError as error:
        raise RuntimeError(
            "Gemini вернул данные неправильной структуры: "
            f"{error}"
        ) from error

    return validated_result.model_dump()
