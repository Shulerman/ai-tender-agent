
import json

from pydantic import ValidationError

from app.ai.gemini import generate_text
from app.ai.legal_models import LegalAnalysis


async def analyze_legal_requirements(document_text: str) -> dict:
    """
    Анализирует закупочную документацию
    и выявляет юридические риски.
    """

    if not document_text.strip():
        raise ValueError("Текст документа пуст")

    prompt = f"""
Ты — опытный специалист по правовому анализу
государственных и коммерческих закупок в Российской Федерации.

Твоя задача — провести подробный аудит предоставленной
закупочной документации с позиции потенциального поставщика.

ВАЖНО: анализируй только переданный текст.
Не утверждай, что изучил документы, которых нет во входных данных.

1. ОПРЕДЕЛЕНИЕ ЗАКУПКИ

Определи:
- применимый закон: 44-ФЗ, 223-ФЗ, коммерческая закупка
  или «Не удалось определить»;
- тип процедуры;
- предмет закупки.

Не путай тип процедуры с применимым законом.

2. АНАЛИЗ УСЛОВИЙ КОНТРАКТА

Проверь отдельно:
- сроки поставки;
- порядок и сроки оплаты;
- порядок приемки;
- штрафы и пени поставщика;
- ответственность заказчика;
- обеспечение заявки и исполнения контракта;
- гарантийные обязательства;
- односторонний отказ;
- порядок изменения и расторжения контракта;
- требования к документам поставщика.

Для каждого найденного условия создай отдельную запись contract_terms.

В поле category используй конкретные названия:
«Срок оплаты», «Срок поставки», «Порядок приемки»,
«Ответственность поставщика» и т. п.

В поле description указывай содержание условия,
а не повторяй название категории.

3. ЮРИДИЧЕСКИЕ РИСКИ

Ищи риски, которые могут привести к:
- отклонению заявки;
- невозможности исполнить контракт;
- дополнительным расходам;
- штрафам и пеням;
- задержке оплаты;
- убыткам поставщика;
- ограничению конкуренции;
- спору с заказчиком.

Каждый риск описывай отдельно.

Уровень риска выбирай строго из списка:
«Критический», «Высокий», «Средний», «Низкий»,
«Не определён».

Не присваивай высокий уровень автоматически.
Объясняй реальную причину риска.

4. ПРИВЯЗКА К ДОКУМЕНТУ

Для каждого условия, риска и противоречия:

- document_clause: точный номер пункта, если он присутствует;
- document_quote: дословная цитата из переданного текста.

Если номер пункта отсутствует, укажи «Не указано».
Если цитату невозможно найти, укажи «Не указано».

Запрещено придумывать номера пунктов и цитаты.
Не выдавай пересказ за дословную цитату.

5. ПРОВЕРКА ЗАКОНОДАТЕЛЬСТВА

Указывай правовые нормы только тогда, когда уверен
в существовании соответствующей нормы и её применимости.

Если актуальность нормы не проверена по официальному
источнику на дату анализа:
- legal_basis_status: «Требует проверки»;
- не называй такую норму проверенной.

Не используй статус «Проверено»:
в рамках этого анализа доступ к официальным правовым
источникам не предоставлен.

Если норма не определена, укажи:
legal_basis: «Не проверено».

6. ПРОТИВОРЕЧИЯ И НЕДОСТАЮЩИЕ ДАННЫЕ

Выявляй:
- противоречия между разделами документа;
- несовпадение сроков и условий;
- неоднозначные требования;
- отсутствие существенных условий;
- сведения, которые невозможно проверить по переданному тексту.

Не называй отсутствием информации то, что просто
не попало в переданный фрагмент документа.
Указывай, что именно требует дополнительного документа.

7. ВОПРОСЫ ЗАКАЗЧИКУ

Составляй конкретные вопросы, ответы на которые
помогут поставщику оценить возможность участия
и финансовые или юридические риски.

8. ИТОГОВОЕ ЗАКЛЮЧЕНИЕ

Кратко укажи:
- общую оценку юридических рисков;
- основные проблемы;
- какие документы необходимо получить;
- что должен проверить специалист перед подачей заявки
  и подписанием контракта.

ОБЩИЕ ЗАПРЕТЫ:

- Не придумывай факты, пункты, цитаты и статьи законов.
- Не считай отсутствие сведений доказательством нарушения закона.
- Не смешивай установленные факты и предположения.
- Не скрывай неопределённость.
- Не делай окончательное юридическое заключение.

Верни только корректный JSON без Markdown.

СТРУКТУРА JSON:

{{
  "procurement_law": "",
  "procurement_type": "",
  "contract_terms": [],
  "risks": [],
  "contradictions": [],
  "missing_information": [],
  "questions_to_customer": [],
  "overall_conclusion": ""
}}

ТЕКСТ ДОКУМЕНТА:

{document_text}
"""

    result = await generate_text(prompt, json_mode=True)
    result = result.strip()

    if result.startswith("```json"):
        result = result[7:]

    elif result.startswith("```"):
        result = result[3:]

    if result.endswith("```"):
        result = result[:-3]

    try:
        parsed_result = json.loads(result.strip())

    except json.JSONDecodeError as error:
        raise RuntimeError(
            f"Gemini вернул некорректный JSON: {error}"
        ) from error

    try:
        validated_result = LegalAnalysis.model_validate(parsed_result)

    except ValidationError as error:
        raise RuntimeError(
            f"Gemini вернул данные неправильной структуры: {error}"
        ) from error

    return validated_result.model_dump()
